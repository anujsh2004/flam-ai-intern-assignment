"""Checks for resources that are not in git, so tests can skip with a fix-it hint.

- FLORES sentence text: regenerated by partA/corpus/prep.py (not committed, D-11)
- gpt2 encoding: tiktoken downloads it on first use (needs network once)
"""
from pathlib import Path

PREPARED = Path(__file__).resolve().parent / "corpus" / "prepared"
FLORES_FILES = [f"{lang}.{split}.txt" for lang in ("eng_Latn", "hin_Deva", "kan_Knda", "tam_Taml")
                for split in ("dev", "devtest")]


def missing_flores(prepared: Path = PREPARED) -> str | None:
    missing = [name for name in FLORES_FILES if not (prepared / name).exists()]
    if not missing:
        return None
    return (f"FLORES text not present ({', '.join(missing)}): run "
            f"`python partA/corpus/prep.py` once (downloads and hash-checks the archive)")


LLAMA = "hf:meta-llama/Llama-3.2-3B@13afe5124825b4f3751f836b40dafda64c1ed062"


def missing_llama() -> str | None:
    """The FLM-4B proxy tokenizer is gated (D-04); graders may not have access."""
    import fertility_v1 as v1

    try:
        v1.load_tokenizer(LLAMA)
    except Exception as exc:
        return (f"Llama-3.2-3B tokenizer unavailable ({type(exc).__name__}): accept the licence at "
                f"https://huggingface.co/meta-llama/Llama-3.2-3B, then run `hf auth login`")
    return None


def missing_gpt2() -> str | None:
    try:
        import tiktoken

        tiktoken.get_encoding("gpt2")
    except Exception as exc:  # network or cache problem on first use
        return f"gpt2 encoding unavailable ({type(exc).__name__}): needs network on first use"
    return None
