#!/usr/bin/env python3
"""Render partA/A3_results.md from partA/analysis/results.json (never hand-typed).

    python partA/analysis/report.py
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
RESULTS = HERE / "results.json"
OUT = ROOT / "partA" / "A3_results.md"
LANGS = ("hin", "kan", "tam")
NAMES = {"gpt2": "gpt2 (REPORT_v0's instrument)", "llama": "Llama-3.2-3B (FLM-4B proxy, serving)",
         "xlmr": "XLM-R (multilingual)", "indicbert": "IndicBERT v2 (Indic-specific)"}


def ci(cell) -> str:
    point, lo, hi = cell
    return f"{point:.3f} [{lo:.3f}, {hi:.3f}]"


def render() -> str:
    r = json.loads(RESULTS.read_text(encoding="utf-8"))
    d = r["design"]
    units = d["units"]
    out = ["# A3 results (generated)", "",
           "_Generated by `python partA/analysis/report.py` from `partA/analysis/results.json`. Do not edit by hand; "
           "a test fails if this file is stale._", "",
           f"Premium vs English = (ΣT_lang/ΣU_lang) / (ΣT_eng/ΣU_eng), the {d['statistic']}, on 2,009 parallel FLORES "
           f"sentences. Brackets: 95% CI from a bootstrap that resamples whole articles ({d['cluster']}), "
           f"{d['n_boot']} resamples, seed {d['seed']}. Text is measured as served (V1: NFC, no lowercasing). "
           "Interpretation is in `partA/A3_analysis.md`.", "",
           "## 1. Premium per parallel sentence (the pre-registered decision number)", "",
           "| tokenizer | hin | kan | tam |", "|---|---|---|---|"]
    for tok, t in r["by_tokenizer"].items():
        out.append(f"| {NAMES[tok]} | " + " | ".join(ci(t["premium"][l]["sentence"]) for l in LANGS) + " |")
    out += ["", "## 2. Same tokens, five denominators", ""]
    for tok, t in r["by_tokenizer"].items():
        out += [f"### {NAMES[tok]}", "", "| lang | " + " | ".join(units) + " |", "|---|" + "---|" * len(units)]
        for l in LANGS:
            out.append(f"| {l} | " + " | ".join(ci(t["premium"][l][u]) for u in units) + " |")
        out.append("")
    out += ["## 3. Per-request overhead (cost-model input side)", "",
            "One request per sentence (worst case), each paying the tokenizer's special tokens. "
            "Premium per sentence, without vs with overhead.", "",
            "| tokenizer | specials/request | " + " | ".join(f"{l} (without → with)" for l in LANGS) + " |",
            "|---|---|" + "---|" * len(LANGS)]
    for tok, t in r["by_tokenizer"].items():
        out.append(f"| {NAMES[tok]} | {t['num_special_tokens']} | " + " | ".join(
            f"{t['premium'][l]['sentence'][0]:.3f} → {t['premium_with_overhead'][l][0]:.3f}" for l in LANGS) + " |")
    out += ["", "## 4. Spread of per-sentence premiums (T_lang,i / T_eng,i)", "",
            "| tokenizer | " + " | ".join(f"{l} median (p10–p90)" for l in LANGS) + " |", "|---|" + "---|" * len(LANGS)]
    for tok, t in r["by_tokenizer"].items():
        out.append(f"| {NAMES[tok]} | " + " | ".join(
            f"{t['spread'][l]['median']:.3f} ({t['spread'][l]['p10']:.3f}–{t['spread'][l]['p90']:.3f})" for l in LANGS) + " |")
    out += ["", "## 5. Token totals (2,009 sentences)", "", "| tokenizer | eng | hin | kan | tam |", "|---|---|---|---|---|"]
    for tok, t in r["by_tokenizer"].items():
        tt = t["tokens_total"]
        out.append(f"| {NAMES[tok]} | {tt['eng']:,} | {tt['hin']:,} | {tt['kan']:,} | {tt['tam']:,} |")
    return "\n".join(out) + "\n"


def main() -> None:
    OUT.write_text(render(), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
